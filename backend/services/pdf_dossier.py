import os
import uuid
from datetime import datetime
from reportlab.lib.pagesizes import letter
from reportlab.pdfgen import canvas
from reportlab.lib import colors
from backend.config import GENERATED_PDFS_DIR

def generate_complaint_dossier(case_data: dict) -> dict:
    """Generates an official-format 1930 Cyber Cell Evidence PDF Dossier."""
    filename = f"ScamDossier_{case_data.get('case_id', 'CASE-2026')}_{uuid.uuid4().hex[:6]}.pdf"
    filepath = GENERATED_PDFS_DIR / filename
    
    c = canvas.Canvas(str(filepath), pagesize=letter)
    width, height = letter
    
    # Header Banner
    c.setFillColor(colors.HexColor("#0f172a")) # Navy
    c.rect(0, height - 80, width, 80, fill=1, stroke=0)
    
    c.setFillColor(colors.white)
    c.setFont("Helvetica-Bold", 16)
    c.drawString(40, height - 45, "NATIONAL CYBER CRIME REPORTING EVIDENCE DOSSIER")
    c.setFont("Helvetica", 10)
    c.drawString(40, height - 62, "Standardized 1930 / I4C Intake Package - Generated by ScamTrap Bharat (Pre-Fraud Honeypot)")
    
    # Metadata Box
    c.setFillColor(colors.HexColor("#f8fafc"))
    c.rect(40, height - 170, width - 80, 75, fill=1, stroke=1)
    
    c.setFillColor(colors.HexColor("#1e293b"))
    c.setFont("Helvetica-Bold", 10)
    c.drawString(55, height - 110, f"INCIDENT REFERENCE ID: {case_data.get('case_id', 'CASE-2026-1001')}")
    c.drawString(55, height - 130, f"CATEGORY: {case_data.get('scam_category', 'Electricity Bill Fraud')}")
    c.drawString(55, height - 150, f"TIMESTAMP: {datetime.now().strftime('%d %B %Y, %I:%M:%S %p')}")
    
    c.drawString(340, height - 110, f"STATUS: CONFIRMED PRE-FRAUD MULE")
    c.drawString(340, height - 130, f"FINANCIAL LOSS: Rs 0 (Interception Complete)")
    c.drawString(340, height - 150, f"TARGET MULE PHONE: {case_data.get('scammer_phone', '+91 98765 43210')}")
    
    # Section 1: Trapped Financial Supply Chain
    c.setFillColor(colors.HexColor("#047857")) # Emerald
    c.setFont("Helvetica-Bold", 13)
    c.drawString(40, height - 205, "1. IDENTIFIED FRAUD FINANCIAL SUPPLY CHAIN (FOR IMMEDIATE FREEZE)")
    
    c.setStrokeColor(colors.HexColor("#cbd5e1"))
    c.line(40, height - 212, width - 40, height - 212)
    
    y = height - 235
    financial_items = [
        ("Primary Extracted Scammer UPI", case_data.get("primary_upi", "bijli.board.pay@ybl")),
        ("Secondary Trapped Bank Account", case_data.get("bank_ac", "50200084729104")),
        ("Beneficiary Bank IFSC Code", case_data.get("ifsc", "SBIN0004821")),
        ("Target Mule Mobile Number", case_data.get("scammer_phone", "9876543210"))
    ]
    
    for label, val in financial_items:
        c.setFillColor(colors.HexColor("#475569"))
        c.setFont("Helvetica-Bold", 10)
        c.drawString(55, y, f"{label}:")
        c.setFillColor(colors.HexColor("#0f172a"))
        c.setFont("Helvetica", 10)
        c.drawString(270, y, str(val))
        y -= 22
        
    # Section 2: Scammer Digital Footprint
    y -= 15
    c.setFillColor(colors.HexColor("#047857"))
    c.setFont("Helvetica-Bold", 13)
    c.drawString(40, y, "2. DIGITAL FORENSICS & CANARY AUDIT LOG")
    c.line(40, y - 7, width - 40, y - 7)
    
    y -= 28
    forensics = [
        ("Trapped Scammer IP Address", case_data.get("ip_address", "103.21.144.62 (Kolkata/Jamtara Substation ISP)")),
        ("Scammer Device Operating System", case_data.get("device_os", "Android 13 (Redmi Note 11)")),
        ("Browser / WhatsApp Client Agent", case_data.get("browser_ua", "Chrome Mobile 122.0.6261.94 / Web-Link-Tracker")),
        ("Counter-Bait Receipt Issued", "UPI Daily Transaction Limit Exceeded (Ref: U30-NPCI)")
    ]
    
    for label, val in forensics:
        c.setFillColor(colors.HexColor("#475569"))
        c.setFont("Helvetica-Bold", 10)
        c.drawString(55, y, f"{label}:")
        c.setFillColor(colors.HexColor("#0f172a"))
        c.setFont("Helvetica", 10)
        c.drawString(270, y, str(val))
        y -= 22

    # Section 3: Conversational Audit Transcript
    y -= 15
    c.setFillColor(colors.HexColor("#047857"))
    c.setFont("Helvetica-Bold", 13)
    c.drawString(40, y, "3. AUTONOMOUS HONEYPOT CHAT TRANSCRIPT (EVIDENCE)")
    c.line(40, y - 7, width - 40, y - 7)
    
    y -= 25
    transcripts = case_data.get("messages", [
        "[SCAMMER]: Dear Consumer, Your Electricity power will be disconnected tonight 9:30 PM...",
        "[DECOY]: Sir please mat kaato light! Kahan pay karna hai batayein?",
        "[SCAMMER]: Pay Rs 45 immediately on our official power UPI: bijli.board.pay@ybl",
        "[DECOY]: Sir maine try kiya par UPI Limit Reached error aa raha hai. Koi alternate account do?",
        "[SCAMMER]: Theek hai is backup account pe transfer karo: A/C 50200084729104 IFSC SBIN0004821"
    ])
    
    for t in transcripts[:6]:
        c.setFillColor(colors.HexColor("#334155"))
        c.setFont("Helvetica", 9)
        c.drawString(55, y, t[:95])
        y -= 18
        
    # Footer
    c.setFillColor(colors.HexColor("#64748b"))
    c.setFont("Helvetica-Oblique", 8)
    c.drawString(40, 30, "Generated via ScamTrap Bharat | Safe Pre-Fraud Co-Pilot & Citizen Cyber Defense System")
    c.drawString(400, 30, "Page 1 of 1 | Verified Integrity Hash: STB-2026-OK")
    
    c.save()
    
    return {
        "filename": filename,
        "filepath": str(filepath),
        "relative_url": f"/storage/generated_pdfs/{filename}"
    }
